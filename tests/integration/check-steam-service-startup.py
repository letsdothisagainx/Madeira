#!/usr/bin/env python3
"""Real PE/SCM integration in a new, disposable Wine prefix.

The I386 service and AMD64 client are explicitly test fixtures, never Valve
replacements. The preparation helper is built from production main.c unchanged.
Native launcher scripts are generated by production Swift in the preceding job.
No account, game installation, user prefix or genuine updater is accessed.
"""
from pathlib import Path
import argparse
import os
import shutil
import re
import struct
import subprocess
import tempfile
import time

ROOT = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser()
parser.add_argument('--script-dir', type=Path, required=True)
args = parser.parse_args()
for tool in ['wine', 'wineboot', 'wineserver', 'i686-w64-mingw32-gcc', 'x86_64-w64-mingw32-gcc']:
    assert shutil.which(tool), 'required integration tool unavailable: ' + tool
for name in ['steam-client.cmd', 'steam-applaunch.cmd']:
    assert (args.script_dir / name).is_file(), 'production Swift script artifact missing'

WINE64 = shutil.which('wine64') or next((str(path) for path in [Path('/usr/lib/wine/wine64'), Path('/usr/lib64/wine/wine64')] if path.is_file()), None)
assert WINE64, 'explicit AMD64 Wine loader unavailable'
MAX_OUTPUT = 4 * 1024 * 1024
with tempfile.TemporaryDirectory(prefix='madeira-service-scm-') as directory:
    temporary = Path(directory)
    prefix = temporary / 'prefix'
    env = {**os.environ, 'WINEPREFIX': str(prefix), 'WINEARCH': 'win64', 'WINEDEBUG': '-all,err+module',
           'WINEDLLOVERRIDES': 'mscoree,mshtml='}
    # No Actions/artifact credentials are passed to the fixture processes.
    for key in list(env):
        if any(word in key.upper() for word in ['TOKEN', 'PASSWORD', 'SECRET', 'CREDENTIAL']):
            env.pop(key)
    def command(argv, timeout=90, expected=0):
        result = subprocess.run(argv, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                timeout=timeout, check=False)
        assert len(result.stdout) <= MAX_OUTPUT, 'fixture output exceeded diagnostic bound'
        text = result.stdout.decode(errors='replace')
        if expected is not None and result.returncode != expected:
            safe = []
            for line in text.splitlines():
                if not any(token in line for token in ['[steam-service]', '[service-fixture]', 'wine:', 'err:module', 'Library ', 'not found']): continue
                line = re.sub(r'https?://[^\s]+', '<url>', line)
                line = re.sub(r"(?:[A-Za-z]:[\\/]|/)[^\"'\r\n]+", '<path>', line)
                safe.append(line[:400])
            raise AssertionError(f'fixture command failed code={result.returncode}; metadata={safe[-25:]!r}')
        return result.returncode, text
    def wine(exe, *arguments, expected=0, timeout=90):
        loader = WINE64 if exe in ['cmd.exe', installed_helper] else 'wine'
        return command([loader, str(exe), *arguments], timeout=timeout, expected=expected)
    def compile_pe(compiler, output, source):
        command([compiler, '-std=c11', '-O1', '-Wall', '-Wextra', '-Werror', '-municode',
                 '-static', '-Wl,--no-insert-timestamp', str(source), '-ladvapi32', '-o', str(output)])
    fixture32, fixture64, helper = [temporary / name for name in ['fixture32.exe', 'fixture64.exe', 'madeira-steam-service.exe']]
    compile_pe('i686-w64-mingw32-gcc', fixture32, ROOT / 'tests/integration/steam-service/fixture.c')
    compile_pe('x86_64-w64-mingw32-gcc', fixture64, ROOT / 'tests/integration/steam-service/fixture.c')
    compile_pe('x86_64-w64-mingw32-gcc', helper, ROOT / 'build/steam-service/main.c')
    for image, expected_machine in [(fixture32, 0x014c), (fixture64, 0x8664), (helper, 0x8664)]:
        data = image.read_bytes(); pe = struct.unpack_from('<I', data, 0x3c)[0]
        assert data[:2] == b'MZ' and data[pe:pe + 4] == b'PE\0\0'
        assert struct.unpack_from('<H', data, pe + 4)[0] == expected_machine
    try:
        command([WINE64, 'wineboot.exe', '--init'], timeout=120)
        fixture = prefix / 'drive_c/Fixture'
        common = fixture / 'Common Files/Steam'
        steam = prefix / 'drive_c/Program Files (x86)/Steam'
        common.mkdir(parents=True, exist_ok=True); steam.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(fixture32, common / 'SteamService.exe')
        shutil.copyfile(fixture32, common / 'SteamServiceTmp.exe')
        control = fixture / 'control32.exe'; shutil.copyfile(fixture32, control)
        shutil.copyfile(fixture64, steam / 'steam.exe')
        installed_helper = prefix / 'drive_c/windows/system32/madeira-steam-service.exe'
        shutil.copyfile(helper, installed_helper)
        protected = {steam / 'config/loginusers.vdf': b'private-auth-fixture-must-stay',
                     steam / 'steamapps/appmanifest_730.acf': b'installed-730-fixture-must-stay',
                     steam / 'steamapps/common/CS2/game/bin/win64/cs2.exe': b'existing-game-fixture-must-stay'}
        for file, data in protected.items():
            file.parent.mkdir(parents=True, exist_ok=True); file.write_bytes(data)
        states = fixture / 'states.fixture'
        wine(control, '--setup', 'early-exit')
        begin = time.monotonic()
        code, output = wine(installed_helper, r'C:\Program Files (x86)\Steam', expected=1053 & 255)
        elapsed = time.monotonic() - begin
        assert '[steam-service] result=1053' in output
        assert '[steam-service] update-witness=0' in output
        assert output.count('[steam-service] start-error=1053') == 1
        assert elapsed < 20, 'early child exit was incorrectly treated as a full startup timeout'
        assert not states.exists(), 'early-exit fixture unexpectedly registered its dispatcher'
        deadline = time.monotonic() + 3
        while True:
            _, status = wine(control, '--query', expected=21)
            if 'query-state=1' in status: break
            assert time.monotonic() < deadline, 'terminated service was not retired by SCM'
            time.sleep(.05)
        print('PASS real I386 early exit zero -> actual SCM/helper1053 before dispatcher; no running state or updater witness invented', flush=True)
        _, enumeration = wine(control, '--pipe-enumeration')
        value = enumeration.split('pipe-enumeration-error=', 1)[1].split()[0]
        assert value.isdigit()
        print('INFO real Wine pipe-enumeration-error=' + value + '; readiness is tested independently through SCM control traffic', flush=True)
        wine(control, '--setup', 'running')
        _, output = wine(installed_helper, r'C:\Program Files (x86)\Steam')
        assert '[steam-service] result=0' in output
        _, status = wine(control, '--query'); assert 'query-state=4' in status
        wine(control, '--stop')
        deadline = time.monotonic() + 3
        while time.monotonic() < deadline:
            if states.exists() and states.read_text().splitlines() == ['2', '4', '3', '1']: break
            time.sleep(.05)
        assert states.read_text().splitlines() == ['2', '4', '3', '1']
        print('PASS real dispatcher/control-pipe connection and SCM pending->running->stop-pending->stopped transitions despite diagnostic enumeration outcome', flush=True)
        states.unlink()
        wine(control, '--setup', 'handoff')
        _, output = wine(installed_helper, r'C:\Program Files (x86)\Steam')
        assert '[steam-service] update-parent-exit=0' in output
        assert '[steam-service] update-witness=1' in output
        assert '[steam-service] update-child-exit=0' in output
        assert '[steam-service] result=0' in output
        _, status = wine(control, '--query'); assert 'query-state=4' in status
        wine(control, '--stop')
        print('PASS real fixture updater lineage/path/held-handle witness, child exit and one SCM retry; this is not a Valve updater compatibility claim', flush=True)
        wine(control, '--setup', 'early-exit')
        client_marker = fixture / 'client-started.fixture'
        for name in ['steam-client.cmd', 'steam-applaunch.cmd']:
            client_marker.unlink(missing_ok=True)
            script = fixture / name; shutil.copyfile(args.script_dir / name, script)
            _, output = wine('cmd.exe', '/d', '/c', 'C:\\Fixture\\' + name, expected=43)
            assert '[steam-service] result=1053' in output
            assert 'policy=steam-managed' in output
            assert '[service-fixture] client-entered=1 exit=43' in output
            assert client_marker.read_bytes() == b'isolated-test-fixture\n'
        assert all(file.read_bytes() == data for file, data in protected.items())
        print('PASS production Swift scripts continue after truthful helper1053 to real AMD64 PE client fixture and preserve its exit43; authentication and game fixtures unchanged', flush=True)
    finally:
        subprocess.run(['wineserver', '-k'], env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                       check=False, timeout=20)
